-- Inline script: defaults to system preference, persists the user choice, and supports mobile touch tap.
themeScript :: String
themeScript = unlines
  [ "(function(){"
  , "  var t=null;"
  , "  try{t=localStorage.getItem('chordbook-theme');}catch(e){}"
  , "  if(!t){t=window.matchMedia&&window.matchMedia('(prefers-color-scheme: light)').matches?'light':'dark';}"
  , "  document.documentElement.setAttribute('data-theme',t);"
  , "})();"
  , "function toggleTheme(){"
  , "  var el=document.documentElement;"
  , "  var next=el.getAttribute('data-theme')==='light'?'dark':'light';"
  , "  el.setAttribute('data-theme',next);"
  , "  try{localStorage.setItem('chordbook-theme',next);}catch(e){}"
  , "}"
  , "document.addEventListener('click',function(e){"
  , "  var target=e.target.closest('.chord-with-hover');"
  , "  var all=document.querySelectorAll('.chord-with-hover.active-popover');"
  , "  for(var i=0;i<all.length;i++){"
  , "    if(all[i]!==target) all[i].classList.remove('active-popover');"
  , "  }"
  , "  if(target){"
  , "    target.classList.toggle('active-popover');"
  , "  }"
  , "});"
  ]
